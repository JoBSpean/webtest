// Трассы. points: [x, z, высота] в метрах; направление движения — по порядку точек.
// Точка 0 — линия старта/финиша. Для реальных картодромов план масштабируется
// до официальной длины (length), форма и порядок поворотов — по схемам трасс (упрощённо).
// pit: пит-лейн вдоль стартовой прямой; side −1 — слева по ходу, +1 — справа;
// before/after — сколько метров до и после линии старта он занимает.

function streets(poly, r) {
  const out = [];
  const n = poly.length;
  for (let i = 0; i < n; i++) {
    const v = poly[i];
    if (v[3] !== 'c') { out.push([v[0], v[1], v[2] || 0]); continue; }
    const p = poly[(i - 1 + n) % n], q = poly[(i + 1) % n];
    const rr = v[4] || r;
    const a = norm(p[0] - v[0], p[1] - v[1]), b = norm(q[0] - v[0], q[1] - v[1]);
    out.push([v[0] + a[0] * rr, v[1] + a[1] * rr, v[2] || 0]);
    out.push([v[0] + (a[0] + b[0]) * rr * 0.29, v[1] + (a[1] + b[1]) * rr * 0.29, v[2] || 0]);
    out.push([v[0] + b[0] * rr, v[1] + b[1] * rr, v[2] || 0]);
  }
  return out;
}
function norm(x, z) { const l = Math.hypot(x, z) || 1; return [x / l, z / l]; }

